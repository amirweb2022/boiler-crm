// =====================================================================
// کاتالوگ ثابت شرکت‌ها — این لیست است که در فرم افزودن شرکت به‌صورت
// دراپ‌داون نمایش داده می‌شود. کد نهایی هر شرکت (catalog_code) همیشه
// از همین‌جا می‌آید، نه از ورودی آزاد کاربر — این یک تصمیم امنیتی و
// یکپارچگی داده است: کد نمی‌تواند جعل یا تکراری وارد شود چون اصلاً از
// سمت کلاینت پذیرفته نمی‌شود؛ فقط شناسه‌ی کاتالوگ (catalogCode) پاس داده
// می‌شود و نام/کد واقعی سمت سرور از همین آرایه استخراج می‌گردد.
//
// برای افزودن شرکت جدید به سیستم: فقط یک آیتم به این آرایه اضافه کنید.
// =====================================================================

export interface CompanyCatalogEntry {
  code: string; // کد یکتا و ثابت، مثال: "AS01"
  name: string; // نام رسمی شرکت
}

export const COMPANIES_CATALOG: CompanyCatalogEntry[] = [
  { code: "AS01", name: "پارس خزر" },
  { code: "AS02", name: "ایران خودرو" },
  { code: "AS03", name: "سایپا" },
  { code: "AS04", name: "فولاد مبارکه" },
  { code: "AS05", name: "پتروشیمی جم" },
  { code: "AS06", name: "لبنیات پگاه" },
  { code: "AS07", name: "کاشی الوند" },
  { code: "AS08", name: "نساجی قائمشهر" },
  { code: "AS09", name: "شیشه قزوین" },
  { code: "AS10", name: "کاغذ سازی پارس" },
];

export function findCatalogEntry(code: string): CompanyCatalogEntry | undefined {
  return COMPANIES_CATALOG.find((c) => c.code === code);
}
